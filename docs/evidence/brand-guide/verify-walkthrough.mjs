import {chromium} from '@playwright/test';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'msedge'});
const page=await browser.newPage({viewport:{width:1600,height:1000},offline:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(pathToFileURL(path.resolve('BenchMate_Brand_Guide.html')).href+'#4');
assert.equal(await page.locator('#walkthrough-video').evaluate(v=>v.paused),true);
await page.getByRole('button',{name:'Next slide'}).click();
assert.equal(await page.locator('.slide:visible').getAttribute('id'),'slide-walkthrough');
await page.waitForFunction(()=>{const v=document.getElementById('walkthrough-video');return v.currentTime>.1&&!v.paused});
const checks=await page.locator('#walkthrough-video').evaluate(v=>({width:v.videoWidth,height:v.videoHeight,duration:v.duration,rate:v.playbackRate,controls:v.controls,fit:getComputedStyle(v).objectFit,embedded:v.querySelector('source').src.startsWith('data:')}));
assert.deepEqual([checks.width,checks.height,checks.rate],[1600,1000,1]);
assert.ok(checks.controls&&checks.embedded);
assert.equal(checks.fit,'contain');
assert.equal(await page.locator('#walkthrough-title').innerText(),'Visual Mockup Walkthrough: 3D Printer Project');
assert.equal(await page.locator('.source,a[href*="behance"]').count(),0);
assert.ok(!/guardbase|behance/i.test(await page.locator('body').innerText()));
await page.locator('#walkthrough-video').evaluate(v=>{v.pause();v.currentTime=8});
await page.waitForFunction(()=>!document.getElementById('walkthrough-video').seeking);
await page.screenshot({path:'docs/evidence/brand-guide/walkthrough-desktop.png'});
await page.getByRole('button',{name:'Next slide'}).click();
assert.equal(await page.locator('.slide:visible').getAttribute('id'),'slide-mockups');
assert.ok(await page.locator('#walkthrough-video').evaluate(v=>v.paused));
await page.getByRole('button',{name:'Previous slide'}).click();
await page.waitForFunction(()=>!document.getElementById('walkthrough-video').paused);
await page.setViewportSize({width:393,height:852});
await page.screenshot({path:'docs/evidence/brand-guide/walkthrough-phone.png'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),393);
await page.emulateMedia({media:'print'});
assert.ok(await page.locator('.walkthrough-print-poster').isVisible());
assert.deepEqual(errors,[]);
checks.errors=errors;checks.navigation=true;checks.hiddenPause=true;checks.referenceRemoved=true;
fs.writeFileSync('docs/evidence/brand-guide/walkthrough-checks.json',JSON.stringify(checks,null,2));
console.log(JSON.stringify(checks,null,2));
await browser.close();
