import {chromium} from '@playwright/test';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'msedge'});
const page=await browser.newPage({viewport:{width:1600,height:1000},offline:true});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(pathToFileURL(path.resolve('BenchMate_Brand_Guide.html')).href+'#6');
await page.evaluate(()=>document.fonts.ready);
await page.waitForFunction(()=>{const v=document.getElementById('mockup-video');return v.readyState>=3&&!v.paused&&v.currentTime>0.1});
const state=()=>page.locator('#mockup-video').evaluate(v=>({time:v.currentTime,rate:v.playbackRate,defaultRate:v.defaultPlaybackRate,paused:v.paused,loop:v.loop,muted:v.muted,width:v.videoWidth,height:v.videoHeight}));
const checks={initial:await state()};
assert.equal(checks.initial.rate,1.75);
assert.equal(checks.initial.defaultRate,1.75);
assert.equal(checks.initial.loop,true);
assert.equal(checks.initial.width,2000);
checks.text=await page.locator('#slide-mockups').innerText();
assert.equal(checks.text.trim(),'Branding Mockups');
assert.equal(await page.locator('.slide').count(),6);
await page.locator('#mockup-video').evaluate(v=>{v.currentTime=2;v.playbackRate=1;v.defaultPlaybackRate=1});
await page.waitForFunction(()=>{const v=document.getElementById('mockup-video');return v.playbackRate===1.75&&v.defaultPlaybackRate===1.75});
checks.enforcedSpeed=await state();
const start=await state();
await page.waitForTimeout(1000);
checks.playbackAdvance=(await state()).time-start.time;
assert.ok(checks.playbackAdvance>1.4&&checks.playbackAdvance<2.1);
await page.screenshot({path:'docs/evidence/brand-guide/mockups/desktop.png'});
await page.locator('#mockup-video').evaluate(v=>{v.currentTime=v.duration-0.2});
await page.waitForFunction(()=>document.getElementById('mockup-video').currentTime<2);
checks.looped=await state();
await page.keyboard.press('ArrowLeft');
await page.waitForFunction(()=>document.getElementById('mockup-video').paused);
checks.hiddenPaused=(await state()).paused;
await page.keyboard.press('End');
await page.waitForFunction(()=>!document.getElementById('mockup-video').paused);
checks.resumed=await state();
checks.images=await page.locator('#slide-mockups img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0));
assert.ok(checks.images);
await page.setViewportSize({width:393,height:852});
await page.screenshot({path:'docs/evidence/brand-guide/mockups/phone.png'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),393);
await page.emulateMedia({media:'print'});
checks.printPoster=await page.locator('.mockup-print-poster').isVisible();
assert.ok(checks.printPoster);
assert.equal(await page.locator('.slide:visible').count(),6);
assert.deepEqual(errors,[]);
checks.errors=errors;
fs.writeFileSync('docs/evidence/brand-guide/mockups/checks.json',JSON.stringify(checks,null,2));
console.log(JSON.stringify(checks,null,2));
await browser.close();
