import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const browser=await chromium.launch({channel:'msedge'});
const context=await browser.newContext({viewport:{width:1600,height:1000},offline:true,reducedMotion:'reduce'});
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
const url=pathToFileURL(path.resolve('BenchMate_Brand_Guide.html')).href+'#2';
await page.goto(url);await page.evaluate(()=>document.fonts.ready);
const checks={reducedMotion:await page.evaluate(()=>benchmateLogoMotion.getState()),frames:[]};
expect(checks.reducedMotion.playing).toBe(false);
for(const value of [0,.25,.5,.75,1]){
  await page.evaluate(v=>benchmateLogoMotion.seek(v),value);
  await page.screenshot({path:`docs/evidence/brand-guide/motion/frame-${String(value*100).padStart(3,'0')}.png`});
  const bounds=await page.locator('canvas').evaluate(c=>JSON.parse(c.dataset.bounds));
  checks.frames.push({position:value,bounds});
  expect(bounds.every(b=>b.minX>=0&&b.maxX<=1538&&b.minY>=0&&b.maxY<=510)).toBe(true);
}
await page.getByRole('button',{name:'Horizontal',exact:true}).click();
expect(await page.evaluate(()=>benchmateLogoMotion.getState().position)).toBe(0);
await page.getByRole('button',{name:'Square',exact:true}).click();
expect(await page.evaluate(()=>benchmateLogoMotion.getState().position)).toBe(1);
await page.getByRole('slider').focus();await page.keyboard.press('Home');
expect(await page.locator('#slide-logo').isVisible()).toBe(true);
expect(await page.evaluate(()=>benchmateLogoMotion.getState().position)).toBe(0);
await page.keyboard.press('ArrowRight');
expect(await page.locator('#slide-logo').isVisible()).toBe(true);
expect(await page.evaluate(()=>benchmateLogoMotion.getState().position)).toBe(.001);
checks.controls='Endpoints and range keyboard controls work without slide navigation';
await page.getByRole('button',{name:'Play Logo Animation'}).click();
await expect.poll(()=>page.evaluate(()=>benchmateLogoMotion.getState().position)).toBeGreaterThan(.02);
await page.getByRole('button',{name:'Pause Logo Animation'}).click();
const paused=await page.evaluate(()=>benchmateLogoMotion.getState());
await page.waitForTimeout(120);
expect(await page.evaluate(()=>benchmateLogoMotion.getState().renderCount)).toBe(paused.renderCount);
checks.pause='Paused frames remain stable';
await page.getByRole('button',{name:'Play Logo Animation'}).click();
await page.getByRole('button',{name:'Next slide'}).click();
const hidden=await page.evaluate(()=>benchmateLogoMotion.getState());
await page.waitForTimeout(120);
expect(await page.evaluate(()=>benchmateLogoMotion.getState().renderCount)).toBe(hidden.renderCount);
checks.offscreen='Animation stops when its slide is hidden';
await page.getByRole('button',{name:'Previous slide'}).click();
await expect.poll(()=>page.evaluate(()=>benchmateLogoMotion.getState().renderCount)).toBeGreaterThan(hidden.renderCount);
checks.resume='Animation resumes on return';
await page.getByRole('button',{name:'Square',exact:true}).click();
await page.setViewportSize({width:393,height:852});
await page.screenshot({path:'docs/evidence/brand-guide/motion/phone.png'});
expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
await page.emulateMedia({media:'print'});
expect(await page.locator('.motion-static').isVisible()).toBe(true);
expect(await page.locator('#logo-motion-canvas').isVisible()).toBe(false);
checks.print='Static wordmark replaces animation in print';
checks.errors=errors;expect(errors).toEqual([]);
fs.writeFileSync('docs/evidence/brand-guide/motion/checks.json',JSON.stringify(checks,null,2));
console.log(JSON.stringify({...checks,frames:checks.frames.map(f=>({position:f.position,contained:true}))},null,2));
await context.close();
const automatic=await browser.newPage({viewport:{width:1600,height:1000},reducedMotion:'no-preference',offline:true});
await automatic.goto(url);
await expect.poll(()=>automatic.evaluate(()=>benchmateLogoMotion.getState().position),{timeout:5000}).toBeGreaterThan(.05);
console.log('Default autoplay verified');
await browser.close();
